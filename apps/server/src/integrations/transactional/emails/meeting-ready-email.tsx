import * as React from 'react';
import {
  Actions,
  B,
  Details,
  ItemList,
  MailBody,
  MailLanguage,
  Note,
  P,
  greeting,
} from '../partials/partials';

export interface MeetingProposalItem {
  title: string;
  meta?: string;
}

interface Props {
  lang: MailLanguage;
  userName?: string;
  meetingTitle: string;
  meetingUrl: string;
  startedAt?: string;
  durationLabel?: string;
  /** Action proposals waiting for a decision (nothing is created without it). */
  proposals?: MeetingProposalItem[];
  /** True when the report could not be generated (partially failed). */
  partial?: boolean;
}

export const MeetingReadyEmail = ({
  lang,
  userName,
  meetingTitle,
  meetingUrl,
  startedAt,
  durationLabel,
  proposals = [],
  partial,
}: Props) => {
  const n = proposals.length;
  const shown = proposals.slice(0, 6);
  const more = n - shown.length;
  if (lang === 'fr') {
    return (
      <MailBody
        lang={lang}
        product="meet"
        icon={n ? 'list-checks-brand' : 'sparkles-brand'}
        preview={
          n
            ? `${n} action${n > 1 ? 's' : ''} proposée${n > 1 ? 's' : ''} à valider.`
            : 'Transcription et compte rendu disponibles.'
        }
        heading={
          partial
            ? 'Votre transcription est prête'
            : 'Votre compte rendu est prêt'
        }
      >
        <P>{greeting(userName, lang)}</P>
        <P>
          {partial ? 'La transcription' : 'Le compte rendu'} de la réunion{' '}
          <B>« {meetingTitle} »</B> est disponible.
          {partial
            ? " Le compte rendu n'a pas pu être généré : vous pouvez le relancer depuis la réunion."
            : ''}
        </P>
        <Details
          rows={[
            ['Date', startedAt],
            ['Durée', durationLabel],
          ]}
        />
        {n > 0 && (
          <>
            <P>
              L'IA a repéré {n === 1 ? 'une action' : `${n} actions`} dans cette
              réunion. Validez, modifiez ou écartez chacune : seules les actions
              validées deviennent des tâches ConqrPlan.
            </P>
            <ItemList numbered items={shown} />
            {more > 0 && (
              <P>
                Et {more} autre{more > 1 ? 's' : ''}.
              </P>
            )}
          </>
        )}
        <Actions
          href={meetingUrl}
          label={n ? 'Valider les actions' : 'Ouvrir le compte rendu'}
        />
        <Note>
          Ce compte rendu est généré par IA à partir de la transcription.
          Relisez-le avant de le partager.
        </Note>
      </MailBody>
    );
  }
  return (
    <MailBody
      lang={lang}
      product="meet"
      icon={n ? 'list-checks-brand' : 'sparkles-brand'}
      preview={
        n
          ? `${n} proposed action${n > 1 ? 's' : ''} to review.`
          : 'Transcript and minutes available.'
      }
      heading={partial ? 'Your transcript is ready' : 'Your minutes are ready'}
    >
      <P>{greeting(userName, lang)}</P>
      <P>
        {partial ? 'The transcript' : 'The minutes'} of the meeting{' '}
        <B>“{meetingTitle}”</B> {partial ? 'is' : 'are'} available.
        {partial
          ? ' The minutes could not be generated: you can restart them from the meeting.'
          : ''}
      </P>
      <Details
        rows={[
          ['Date', startedAt],
          ['Duration', durationLabel],
        ]}
      />
      {n > 0 && (
        <>
          <P>
            The AI spotted {n === 1 ? 'one action' : `${n} actions`} in this
            meeting. Approve, edit or dismiss each one: only approved actions
            become ConqrPlan tasks.
          </P>
          <ItemList numbered items={shown} />
          {more > 0 && (
            <P>
              And {more} more.
            </P>
          )}
        </>
      )}
      <Actions
        href={meetingUrl}
        label={n ? 'Review the actions' : 'Open the minutes'}
      />
      <Note>
        These minutes are generated by AI from the transcript. Read them over
        before sharing them.
      </Note>
    </MailBody>
  );
};

export default MeetingReadyEmail;
